def run_checks(args: argparse.Namespace, output: Path, record: dict) -> None:
    inputs = original_inputs()
    overlay_content = OVERLAY.read_bytes()
    require(hashlib.sha256(overlay_content).hexdigest() == OVERLAY_SHA, "Overlay SHA mismatch")
    for path, sha, _ in inputs:
        require(digest(path) == sha, f"Pinned original input mismatch: {path}")
    record["input_sha256"] = {str(path): sha for path, sha, _ in inputs}
    deadline = time.monotonic() + 120.0
    logs = output / "logs"
    logs.mkdir()
    with tempfile.TemporaryDirectory(prefix="flash-f32-overlay-", dir=output) as owned:
        workspace = Path(owned)
        owned_overlay = workspace / "flash_f32_overlay.cmake"
        owned_overlay.write_bytes(overlay_content)
        source = workspace / "source"
        source.mkdir()
        for path, _, relative in inputs:
            target = source / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
        (source / "CMakeLists.txt").write_text(cmake_project(owned_overlay))

        def configure(name: str, flags: tuple[str, ...] = ()) -> tuple[Path, int, str]:
            build = workspace / name
            remaining = deadline - time.monotonic()
            require(remaining > 0, "Configure-only verification deadline expired")
            command = [args.cmake, "-S", str(source), "-B", str(build), "-G", "Ninja", *flags]
            completed = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                       text=True, timeout=min(20.0, remaining), check=False)
            (logs / f"{name}.log").write_text(completed.stdout)
            return build, completed.returncode, completed.stdout

        build, code, text = configure("positive")
        require(code == 0, f"Positive configure failed: {text[-2000:]}")
        facts = dict(line.split("=", 1) for line in (build / "facts.txt").read_text().splitlines())
        pipeline = build / "conflux-flash-f32/pipeline.cpp"
        vulkan = build / "conflux-flash-f32/ggml-vulkan.cpp"
        require(facts == {"pipeline": str(pipeline), "vulkan": str(vulkan),
                          "model_sources": str(pipeline), "vulkan_sources": str(vulkan)},
                "Candidate did not replace exactly the two expected target sources")
        actual_generated = {"pipeline.cpp": digest(pipeline), "ggml-vulkan.cpp": digest(vulkan)}
        require(actual_generated == EXPECTED_GENERATED,
                "Generated candidate differs from the independent real-configure source hashes")
        require(digest(source / "baseline/pipeline.h") == GENERATED_PINS["pipeline.h"][1],
                "Generated phase header changed")
        record["generated_sha256"] = actual_generated
        record["checks"].append({"name": "positive_exact_sources_and_unchanged_header", "passed": True})

        tamper_cases = {
            "upstream-pipeline": "upstream/src/models/demucs/pipeline.cpp",
            "upstream-header": "upstream/include/engine/models/demucs/pipeline.h",
            "upstream-vulkan": "upstream/external/ggml/src/ggml-vulkan/ggml-vulkan.cpp",
            "public-interface": "upstream/external/ggml/include/ggml-backend.h",
            "shader": "upstream/external/ggml/src/ggml-vulkan/vulkan-shaders/flash_attn.comp",
            "generator": "GraphPhaseTiming.cmake",
            "generated-phase": "baseline/pipeline.cpp",
            "generated-blocking": "baseline/ggml-vulkan.cpp",
        }
        for name, relative in tamper_cases.items():
            target = source / relative
            original = target.read_bytes()
            try:
                target.write_bytes(original + b"\n// owned verification tamper\n")
                case_build, code, text = configure(name)
                require(code != 0 and "input hash mismatch:" in text, f"Tampered {name} was not hash-rejected")
                require(not (case_build / "conflux-flash-f32").exists(), f"Tampered {name} wrote candidate outputs")
            finally:
                target.write_bytes(original)
            record["checks"].append({"name": name, "passed": True})

        case_build, code, text = configure("invalid-target-mapping", ("-DFLASH_BAD_MAPPING=ON",))
        require(code != 0 and "expected source copies are not target sources" in text,
                "Invalid target mapping was not rejected")
        require(not (case_build / "conflux-flash-f32").exists(), "Invalid target mapping wrote candidate outputs")
        record["checks"].append({"name": "invalid_target_mapping", "passed": True})

        case_build, code, text = configure("repeat-include", ("-DFLASH_REPEAT_INCLUDE=ON",))
        require(code != 0 and "expected source copies are not target sources" in text,
                "Repeated overlay inclusion was not rejected")
        require({name: digest(case_build / "conflux-flash-f32" / name) for name in actual_generated}
                == actual_generated, "Repeated inclusion modified the first valid candidate outputs")
        record["checks"].append({"name": "repeat_include_rejected_first_outputs_unchanged", "passed": True})
        for path, sha, relative in inputs:
            require(digest(source / relative) == sha, f"Owned fixture was not restored: {relative}")
            require(digest(path) == sha, f"Original input changed: {path}")
        record["originals_unchanged"] = True
    record["owned_workspace_removed"] = not Path(owned).exists()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--cmake", default="cmake")
    args = parser.parse_args()
    if not args.run:
        print(json.dumps({"status": "dry_plan", "overlay_sha256": OVERLAY_SHA,
                          "scope": "project(NONE), configure only; no compiler/build/native/model",
                          "cases": "positive, eight pin classes, invalid source mapping, repeated include"}))
        return 0
    if args.output is None:
        parser.error("--run requires a new --output directory")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    started = time.monotonic()
    record = {"schema": 1, "status": "incomplete", "scope": "CMake configure only; no build/native or numerical proof",
              "overlay_sha256": OVERLAY_SHA, "verifier_sha256": digest(Path(__file__)),
              "build_executed": False, "native_executed": False, "checks": []}
    try:
        run_checks(args, output, record)
        record["status"] = "passed"
    except Exception as exc:
        record["status"] = "failed"
        record["error"] = f"{type(exc).__name__}: {exc}"
    finally:
        record["elapsed_seconds"] = time.monotonic() - started
        (output / "result.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps(record))
    return 0 if record["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
