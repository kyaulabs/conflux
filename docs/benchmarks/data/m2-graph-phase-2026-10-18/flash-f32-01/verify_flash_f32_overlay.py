def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def original_inputs() -> list[tuple[Path, str, Path]]:
    rows = [(UPSTREAM / name, sha, Path("upstream") / name) for name, sha in UPSTREAM_PINS.items()]
    rows += [(REPO / "tools/runtime" / name, sha, Path(name)) for name, sha in LOCAL_PINS.items()]
    rows += [(path, sha, Path("baseline") / name) for name, (path, sha) in GENERATED_PINS.items()]
    return rows


